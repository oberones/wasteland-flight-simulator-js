/** Validate the authored asset and embed it without adding runtime file requests. */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

const root = new URL("./", import.meta.url);
const htmlPath = new URL("../../index.html", root);
const marker =
  /\/\/ BEGIN DUSTKITE GEOMETRY[\s\S]*?\/\/ END DUSTKITE GEOMETRY/g;
const geometryBytes = await readFile(new URL("geometry.json", root));
const geometry = JSON.parse(geometryBytes.toString());
const manifest = JSON.parse(
  await readFile(new URL("manifest.json", root), "utf8"),
);

/** Return a stable content digest for source/export consistency checks. */
function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const { positions, normals, colors, indices } = geometry;
assert.deepEqual(Object.keys(geometry).sort(), [
  "colors",
  "indices",
  "normals",
  "positions",
]);
assert(positions.length > 0 && positions.length % 3 === 0, "invalid positions");
assert.equal(normals.length, positions.length);
assert.equal(colors.length, positions.length);
assert(indices.length > 0 && indices.length % 3 === 0, "invalid triangles");
assert(indices.length / 3 <= 2500, "triangle budget exceeded");
assert(positions.every(Number.isFinite), "non-finite position");
assert(normals.every(Number.isFinite), "non-finite normal");
assert(
  colors.every((value) => Number.isFinite(value) && value >= 0 && value <= 1),
  "invalid linear color",
);
assert(
  indices.every(
    (value) =>
      Number.isInteger(value) && value >= 0 && value < positions.length / 3,
  ),
  "invalid index",
);
const bounds = { min: [], max: [] };
for (let axis = 0; axis < 3; axis += 1) {
  const values = positions.filter((_value, index) => index % 3 === axis);
  bounds.min.push(Math.min(...values));
  bounds.max.push(Math.max(...values));
  assert(bounds.min[axis] >= [-8.5, -1, -5.8][axis], "minimum bound exceeded");
  assert(bounds.max[axis] <= [8.5, 2.5, 5.5][axis], "maximum bound exceeded");
}
for (let i = 0; i < normals.length; i += 3) {
  assert(
    Math.abs(Math.hypot(...normals.slice(i, i + 3)) - 1) < 0.00003,
    "non-unit normal",
  );
}
for (let i = 0; i < indices.length; i += 3) {
  const [a, b, c] = indices
    .slice(i, i + 3)
    .map((value) => positions.slice(value * 3, value * 3 + 3));
  const u = b.map((value, axis) => value - a[axis]);
  const v = c.map((value, axis) => value - a[axis]);
  assert(
    Math.hypot(
      u[1] * v[2] - u[2] * v[1],
      u[2] * v[0] - u[0] * v[2],
      u[0] * v[1] - u[1] * v[0],
    ) > 1e-9,
    "degenerate triangle",
  );
}
assert.equal(manifest.vertices, positions.length / 3);
assert.equal(manifest.triangles, indices.length / 3);
assert.deepEqual(manifest.bounds, bounds);
assert.equal(
  manifest.geometrySha256,
  sha256(geometryBytes),
  "stale export manifest",
);
assert.equal(
  manifest.sourceSha256,
  sha256(await readFile(new URL("dustkite.blend", root))),
  "stale Blender source manifest",
);
for (const [name, hash] of Object.entries(manifest.scriptsSha256)) {
  assert.equal(
    hash,
    sha256(await readFile(new URL(name, root))),
    `stale script manifest: ${name}`,
  );
}
const html = await readFile(htmlPath, "utf8");
assert.equal(
  [...html.matchAll(marker)].length,
  1,
  "exactly one geometry marker is required",
);
const replacement = `// BEGIN DUSTKITE GEOMETRY\n// Generated by npm run glider:embed; edit the Blender source instead.\nconst GLIDER_GEOMETRY = deepFreeze(${JSON.stringify(geometry)});\n// END DUSTKITE GEOMETRY`;
const embedded = await format(
  html.replace(marker, () => replacement),
  { parser: "html" },
);
const block = [...embedded.matchAll(marker)][0][0];
assert(
  Buffer.byteLength(block) <= 750 * 1024,
  "embedded geometry exceeds 750 KiB",
);
if (process.argv.includes("--check")) {
  assert.equal(
    html,
    embedded,
    "embedded geometry drift: run npm run glider:embed",
  );
} else {
  await writeFile(htmlPath, embedded);
}
console.log(
  JSON.stringify({
    status: "PASS",
    vertices: manifest.vertices,
    triangles: manifest.triangles,
    bounds,
    embeddedBytes: Buffer.byteLength(block),
    geometrySha256: manifest.geometrySha256,
  }),
);
