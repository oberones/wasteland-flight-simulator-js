/** Validate Blender provenance and geometry before embedding the building collection. */
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { format } from "prettier";

const root = new URL("./", import.meta.url);
const htmlPath = new URL("../../index.html", root);
const marker =
  /\/\/ BEGIN BUILDING GEOMETRY[\s\S]*?\/\/ END BUILDING GEOMETRY/g;
const bytes = await readFile(new URL("geometry.json", root));
const geometry = JSON.parse(bytes.toString());
const manifest = JSON.parse(
  await readFile(new URL("manifest.json", root), "utf8"),
);

/** Hash the exact delivered bytes, including source and export tooling. */
function hash(value) {
  return createHash("sha256").update(value).digest("hex");
}

/** Reject malformed geometry, stale bounds, and discontinuous named part ranges. */
function validateBuffer(buffer) {
  const { positions, normals, colors, indices, parts, bounds } = buffer;
  assert(
    positions.length > 0 && positions.length % 3 === 0,
    "invalid positions",
  );
  assert.equal(normals.length, positions.length);
  assert.equal(colors.length, positions.length);
  assert(positions.every(Number.isFinite), "non-finite position");
  assert(normals.every(Number.isFinite), "non-finite normal");
  assert(
    colors.every((v) => Number.isFinite(v) && v >= 0 && v <= 1),
    "invalid color",
  );
  assert(indices.length > 0 && indices.length % 3 === 0, "invalid triangles");
  assert(
    indices.every(
      (v) => Number.isInteger(v) && v >= 0 && v < positions.length / 3,
    ),
    "invalid index",
  );
  for (let i = 0; i < normals.length; i += 3)
    assert(
      Math.abs(Math.hypot(...normals.slice(i, i + 3)) - 1) < 0.00003,
      "non-unit normal",
    );
  for (let axis = 0; axis < 3; axis += 1) {
    const values = positions.filter((_v, i) => i % 3 === axis);
    assert.equal(bounds.min[axis], Math.min(...values));
    assert.equal(bounds.max[axis], Math.max(...values));
    assert(
      bounds.min[axis] >= [-0.5, -0.5, -0.5][axis],
      "minimum bound exceeded",
    );
    assert(bounds.max[axis] <= [0.5, 1, 0.5][axis], "maximum bound exceeded");
  }
  for (let i = 0; i < indices.length; i += 3) {
    const [a, b, c] = indices
      .slice(i, i + 3)
      .map((v) => positions.slice(v * 3, v * 3 + 3));
    const u = b.map((v, j) => v - a[j]),
      v = c.map((v, j) => v - a[j]);
    assert(
      Math.hypot(
        u[1] * v[2] - u[2] * v[1],
        u[2] * v[0] - u[0] * v[2],
        u[0] * v[1] - u[1] * v[0],
      ) > 1e-10,
      "degenerate triangle",
    );
  }
  let offset = 0;
  const names = new Set();
  for (const part of parts) {
    assert(
      typeof part.name === "string" &&
        part.name.length > 0 &&
        !names.has(part.name),
      "invalid part name",
    );
    names.add(part.name);
    assert.equal(part.firstIndex, offset, "noncontiguous part range");
    assert(
      Number.isInteger(part.indexCount) &&
        part.indexCount > 0 &&
        part.indexCount % 3 === 0,
      "invalid part range",
    );
    offset += part.indexCount;
  }
  assert.equal(offset, indices.length, "incomplete part ranges");
}

assert.equal(geometry.schemaVersion, 1);
assert.deepEqual(Object.keys(geometry.models).sort(), [
  "industrial",
  "office",
  "residential",
  "shell",
]);
assert.deepEqual(
  Object.keys(manifest.models).sort(),
  Object.keys(geometry.models).sort(),
);
for (const [id, model] of Object.entries(geometry.models)) {
  validateBuffer(model.body);
  validateBuffer(model.windows);
  const triangles =
    (model.body.indices.length + model.windows.indices.length) / 3;
  assert(triangles <= 1000, `${id}: triangle budget exceeded`);
  assert.deepEqual(manifest.models[id], {
    triangles,
    bodyVertices: model.body.positions.length / 3,
    windowVertices: model.windows.positions.length / 3,
    windowPanels: model.windows.parts.length,
    bounds: model.body.bounds,
  });
}
assert.equal(manifest.geometrySha256, hash(bytes), "stale export manifest");
assert.equal(
  manifest.sourceSha256,
  hash(await readFile(new URL("buildings.blend", root))),
  "stale source manifest",
);
for (const name of [
  "create_scene.py",
  "export_geometry.py",
  "render_previews.py",
  "embed-geometry.js",
])
  assert.equal(
    manifest.scriptsSha256[name],
    hash(await readFile(new URL(name, root))),
    `stale script: ${name}`,
  );
const html = await readFile(htmlPath, "utf8");
assert.equal(
  [...html.matchAll(marker)].length,
  1,
  "exactly one building geometry marker required",
);
const replacement = `// BEGIN BUILDING GEOMETRY\n// Generated by npm run buildings:embed; edit the Blender source instead.\nconst BUILDING_GEOMETRY = deepFreeze(${JSON.stringify(geometry)});\n// END BUILDING GEOMETRY`;
const embedded = await format(
  html.replace(marker, () => replacement),
  { parser: "html" },
);
const embeddedBytes = Buffer.byteLength([...embedded.matchAll(marker)][0][0]);
assert(embeddedBytes <= 1048576, "building embedding exceeds 1 MiB");
if (process.argv.includes("--check"))
  assert.equal(html, embedded, "building embedding drift");
else await writeFile(htmlPath, embedded);
console.log(
  JSON.stringify({
    status: "PASS",
    embeddedBytes,
    models: manifest.models,
    geometrySha256: manifest.geometrySha256,
  }),
);
